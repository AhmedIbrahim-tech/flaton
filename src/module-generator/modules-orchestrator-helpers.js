/**
 * Shared path, DbSet, registry, and summary helpers used by the V4 application
 * module generators (users, permissions, audit, notifications).
 *
 * Every generator returns a normalized plan object of the shape:
 *
 *   {
 *     id: ModuleId,
 *     requires: ModuleId[],
 *     files: { relativePath, contents, writeMode? }[],
 *     registryUpdates: { relativePath, update(existing): string }[],
 *     registrations: { method, namespace }[], // DI extension methods to wire up
 *     packages: { backend?: string[], react?: string[], angular?: string[] },
 *     summary: { total, backend, frontend, registryUpdates, registrations },
 *   }
 *
 * The plan object is intentionally declarative: it never touches the filesystem
 * itself. A future orchestrator (module-index.js) is expected to write the
 * planned files, apply registry updates, and call the DI registrations.
 */

import { getBackendFilePath, getFrontendFilePath } from '../utils/project-paths.js';
import {
  planRouterUpdate,
  upsertContextDbSet,
  upsertInterfaceDbSet,
} from '../feature-generator/backend/clean-architecture.js';

const AUTO_HEADER_TS = `// AUTO-GENERATED BY create-fullstack-module
// DO NOT EDIT MANUALLY`;

let currentManifestContext = null;

export function setModuleManifestContext(manifest) {
  currentManifestContext = manifest;
}

/**
 * Relative-path builders anchored at the project root. Using these keeps the
 * generators consistent with the feature generator's layout conventions.
 */
export const paths = {
  /** @param {...string} segments */
  domain: (...segments) => getBackendFilePath(currentManifestContext, 'Domain', ...segments),
  /** @param {...string} segments */
  application: (...segments) => getBackendFilePath(currentManifestContext, 'Application', ...segments),
  /** @param {...string} segments */
  infrastructure: (...segments) => getBackendFilePath(currentManifestContext, 'Infrastructure', ...segments),
  /** @param {...string} segments */
  api: (...segments) => getBackendFilePath(currentManifestContext, 'API', ...segments),
  /** @param {...string} segments */
  web: (...segments) => getBackendFilePath(currentManifestContext, 'Web', ...segments),
  /** @param {...string} segments */
  client: (...segments) => getFrontendFilePath(currentManifestContext, 'src', ...segments),
  /**
   * @param {string} kebabModule
   * @param {...string} segments
   */
  reactModule: (kebabModule, ...segments) =>
    getFrontendFilePath(currentManifestContext, 'src', 'modules', kebabModule, ...segments),
  /**
   * @param {string} kebabFeature
   * @param {...string} segments
   */
  angularFeature: (kebabFeature, ...segments) =>
    getFrontendFilePath(currentManifestContext, 'src', 'app', 'features', kebabFeature, ...segments),
};

/**
 * Whether the resolved frontend strategy is React (Next.js or Vite).
 * @param {object} config
 */
export function isReact(config) {
  return config?.frontendStrategy?.library === 'react';
}

/**
 * Whether the resolved frontend strategy is Angular.
 * @param {object} config
 */
export function isAngular(config) {
  return config?.frontendStrategy?.library === 'angular';
}

/**
 * Whether the React app uses the Next.js App Router (vs. Vite + react-router).
 * @param {object} config
 */
export function isNext(config) {
  return (
    isReact(config) && config?.frontendStrategy?.framework === 'next'
  );
}

/**
 * Build the two persistence partials (interface + context) that expose an
 * entity as a DbSet without editing the hand-authored context files.
 *
 * @param {string} projectName
 * @param {string} singularEntity  e.g. "Notification"
 * @param {string} pluralDbSet     e.g. "Notifications"
 * @returns {{ relativePath: string, contents: string }[]}
 */
/**
 * Upsert a DbSet onto the canonical persistence files.
 *
 * @param {string} projectName
 * @param {string} singularEntity
 * @param {string} pluralDbSet
 */
export function dbSetUpdates(projectName, singularEntity, pluralDbSet, entityNamespace) {
  return [
    {
      relativePath: paths.application(
        'Abstractions',
        'Persistence',
        'IApplicationDbContext.cs',
      ),
      update: (existing) =>
        upsertInterfaceDbSet(
          existing,
          projectName,
          singularEntity,
          pluralDbSet,
          entityNamespace,
        ),
    },
    {
      relativePath: paths.infrastructure('Persistence', 'ApplicationDbContext.cs'),
      update: (existing) =>
        upsertContextDbSet(
          existing,
          projectName,
          singularEntity,
          pluralDbSet,
          entityNamespace,
        ),
    },
  ];
}

/**
 * @deprecated Use dbSetUpdates registry entries instead of partial *.g.cs files.
 */
export function dbSetPartials(projectName, singularEntity, pluralDbSet) {
  return dbSetUpdates(projectName, singularEntity, pluralDbSet);
}

export function routerUpdate(projectName, className, resourcePath, routes) {
  return planRouterUpdate(currentManifestContext, projectName, className, resourcePath, routes);
}

/**
 * The ICurrentUser abstraction every authenticated module relies on to resolve
 * the acting user id. Emitted with writeMode "ifMissing" so the auth module (or
 * another feature module) can own the canonical copy without conflicts.
 *
 * @param {string} projectName
 * @returns {{ relativePath: string, contents: string, writeMode: string }[]}
 */
export function currentUserAbstraction(projectName) {
  const ns = projectName;
  const isWeb = currentManifestContext?.backend?.presentation === 'mvc' || currentManifestContext?.backend?.presentation === 'razor-pages';
  const targetFolder = isWeb ? 'Web' : 'API';
  const targetFn = isWeb ? paths.web : paths.api;
  return [
    {
      writeMode: 'ifMissing',
      relativePath: paths.application('Abstractions', 'Identity', 'ICurrentUser.cs'),
      contents: `namespace ${ns}.Application.Abstractions.Identity;

public interface ICurrentUser
{
    Guid? UserId { get; }

    bool IsAuthenticated { get; }

    string? Email { get; }

    IReadOnlyList<string> Roles { get; }

    IReadOnlyList<string> Permissions { get; }
}
`,
    },
    {
      writeMode: 'ifMissing',
      relativePath: targetFn('Services', 'CurrentUserService.cs'),
      contents: `using System.IdentityModel.Tokens.Jwt;
using System.Security.Claims;
using Microsoft.AspNetCore.Http;
using ${ns}.Application.Abstractions.Identity;

namespace ${ns}.${targetFolder}.Services;

public sealed class CurrentUserService : ICurrentUser
{
    private readonly IHttpContextAccessor _httpContextAccessor;

    public CurrentUserService(IHttpContextAccessor httpContextAccessor)
    {
        _httpContextAccessor = httpContextAccessor;
    }

    private ClaimsPrincipal? Principal => _httpContextAccessor.HttpContext?.User;

    public bool IsAuthenticated => Principal?.Identity?.IsAuthenticated ?? false;

    public Guid? UserId
    {
        get
        {
            var value = Principal?.FindFirstValue(JwtRegisteredClaimNames.Sub)
                ?? Principal?.FindFirstValue(ClaimTypes.NameIdentifier);
            return Guid.TryParse(value, out var id) ? id : null;
        }
    }

    public string? Email =>
        Principal?.FindFirstValue(JwtRegisteredClaimNames.Email)
        ?? Principal?.FindFirstValue(ClaimTypes.Email);

    public IReadOnlyList<string> Roles =>
        Principal?.FindAll(ClaimTypes.Role).Select(claim => claim.Value).ToList()
        ?? new List<string>();

    public IReadOnlyList<string> Permissions =>
        Principal?.FindAll("permission").Select(claim => claim.Value).ToList()
        ?? new List<string>();
}
`,
    },
  ];
}

/**
 * Build a DI registration extension file for a module's Infrastructure wiring.
 * Returns both the planned file and a registration descriptor the orchestrator
 * can use to invoke the extension method during AddInfrastructure.
 *
 * @param {object} options
 * @param {string} options.projectName
 * @param {string} options.moduleName    PascalCase module, e.g. "Notifications"
 * @param {string[]} [options.usings]    extra using statements
 * @param {string[]} options.body        registration statements (already indented 8 spaces)
 * @returns {{ file: { relativePath: string, contents: string }, registration: { method: string, namespace: string } }}
 */
export function moduleRegistrationFile(options) {
  const { projectName: ns, moduleName, usings = [], body } = options;
  const method = `Add${moduleName}Module`;
  const namespace = `${ns}.Infrastructure.DependencyInjection`;
  const usingBlock = usings.length > 0 ? `${usings.join('\n')}\n` : '';

  return {
    registration: { method, namespace },
    file: {
      relativePath: paths.infrastructure(
        'DependencyInjection',
        `${moduleName}ServiceExtensions.cs`,
      ),
      contents: `using Microsoft.Extensions.DependencyInjection;
${usingBlock}
namespace ${namespace};

public static class ${moduleName}ServiceExtensions
{
    public static IServiceCollection ${method}(this IServiceCollection services)
    {
${body.join('\n')}

        return services;
    }
}
`,
    },
  };
}

