/**
 * Normalize a raw plan into the standard module plan object and compute the
 * file-list summary.
 *
 * @param {object} plan
 * @param {string} plan.id
 * @param {string[]} [plan.requires]
 * @param {{ relativePath: string, contents: string, writeMode?: string }[]} plan.files
 * @param {{ relativePath: string, update: (existing: string) => string }[]} [plan.registryUpdates]
 * @param {{ method: string, namespace: string }[]} [plan.registrations]
 * @param {{ backend?: string[], react?: string[], angular?: string[] }} [plan.packages]
 * @param {string[]} [plan.notes]
 */
export function finalizePlan(plan) {
  const files = plan.files ?? [];
  const backendCount = files.filter((file) =>
    /^(Backend[\\/]|Domain[\\/]|Application[\\/]|Infrastructure[\\/]|API[\\/])/.test(file.relativePath),
  ).length;
  const frontendCount = files.filter((file) =>
    /^(Frontend[\\/]|Client[\\/]|src[\\/])/.test(file.relativePath),
  ).length;

  return {
    id: plan.id,
    requires: plan.requires ?? [],
    files,
    registryUpdates: plan.registryUpdates ?? [],
    registrations: plan.registrations ?? [],
    packages: plan.packages ?? {},
    notes: plan.notes ?? [],
    summary: {
      total: files.length,
      backend: backendCount,
      frontend: frontendCount,
      registryUpdates: (plan.registryUpdates ?? []).length,
      registrations: (plan.registrations ?? []).length,
    },
  };
}

