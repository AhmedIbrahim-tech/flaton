/**
 * @param {string} content
 * @param {string} importLine
 */
export function ensureImport(content, importLine) {
  if (content.includes(importLine)) {
    return content;
  }

  const lines = content.split('\n');
  let lastImport = -1;
  for (let index = 0; index < lines.length; index += 1) {
    if (/^import\s/.test(lines[index])) {
      lastImport = index;
    }
  }

  if (lastImport === -1) {
    const headerEnd = content.indexOf('\n\n');
    if (headerEnd !== -1) {
      return `${content.slice(0, headerEnd)}\n\n${importLine}${content.slice(headerEnd)}`;
    }
    return `${importLine}\n${content}`;
  }

  lines.splice(lastImport + 1, 0, importLine);
  return lines.join('\n');
}

/**
 * @param {string} content
 * @param {string} objectName
 * @param {string} entryLine
 */
export function ensureObjectEntry(content, objectName, entryLine) {
  const emptyPattern = new RegExp(`export const ${objectName} = \\{\\};`);
  if (emptyPattern.test(content)) {
    return content.replace(
      emptyPattern,
      `export const ${objectName} = {\n${entryLine}\n};`,
    );
  }

  const filledPattern = new RegExp(
    `(export const ${objectName} = \\{)([\\s\\S]*?)(\\n\\};)`,
  );
  return content.replace(filledPattern, (match, open, inner, close) => {
    const body = inner.replace(/\s+$/, '');
    return `${open}${body}\n${entryLine}${close}`;
  });
}

/**
 * @param {string} content
 * @param {string} arrayName
 * @param {string} entry
 * @param {string} marker
 */
export function ensureArrayEntry(content, arrayName, entry, marker) {
  if (content.includes(marker)) {
    return content;
  }

  const emptyPattern = new RegExp(
    `export const ${arrayName}: DashboardNavItem\\[\\] = \\[\\];`,
  );
  if (emptyPattern.test(content)) {
    return content.replace(
      emptyPattern,
      `export const ${arrayName}: DashboardNavItem[] = [\n${entry}\n];`,
    );
  }

  const filledPattern = new RegExp(
    `(export const ${arrayName}: DashboardNavItem\\[\\] = \\[)([\\s\\S]*?)(\\n\\];)`,
  );
  return content.replace(filledPattern, (match, open, inner, close) => {
    const body = inner.replace(/\s+$/, '');
    return `${open}${body}\n${entry}${close}`;
  });
}

