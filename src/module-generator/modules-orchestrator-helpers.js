/**
 * Idempotently register a module reducer in the generated reducers file.
 *
 * @param {object} options
 * @param {string} options.reducerKey   store slice key, e.g. "notifications"
 * @param {string} options.importName   default import binding, e.g. "notificationsReducer"
 * @param {string} options.importPath   module-relative import, e.g. "@/modules/notifications/slices/notifications.slice"
 * @returns {(existing: string) => string}
 */
export function reactReducerUpdate(options) {
  const { reducerKey, importName, importPath } = options;
  const importLine = `import ${importName} from "${importPath}";`;
  const entryLine = `  ${reducerKey}: ${importName},`;

  return (existing) => {
    let content =
      existing && existing.trim().length > 0
        ? existing
        : `${AUTO_HEADER_TS}\n\nexport const generatedReducers = {};\n`;

    if (content.includes(entryLine)) {
      return content;
    }

    content = ensureImport(content, importLine);
    content = ensureObjectEntry(content, 'generatedReducers', entryLine);
    return content;
  };
}

/**
 * Idempotently register a dashboard nav item in the generated nav file.
 *
 * @param {object} options
 * @param {string} options.navKey       i18n key suffix, e.g. "users"
 * @param {string} options.label        human label, e.g. "Users"
 * @param {string} options.href         route, e.g. "/dashboard/users"
 * @param {string} [options.icon]       lucide icon name, defaults to "Boxes"
 * @returns {(existing: string) => string}
 */
export function reactDashboardNavUpdate(options) {
  const { navKey, label, href, icon = 'Boxes' } = options;

  return (existing) => {
    let content =
      existing && existing.trim().length > 0
        ? existing
        : defaultReactNav();

    const hrefMarker = `href: "${href}"`;
    if (content.includes(hrefMarker)) {
      return content;
    }

    content = ensureImport(content, `import { ${icon} } from "lucide-react";`);

    const entry = `  {
    labelKey: "nav.${navKey}",
    label: ${JSON.stringify(label)},
    href: "${href}",
    icon: ${icon},
  },`;

    content = ensureArrayEntry(content, 'generatedDashboardNav', entry, hrefMarker);
    return content;
  };
}

/**
 * @returns {string}
 */
function defaultReactNav() {
  return `${AUTO_HEADER_TS}

import type { LucideIcon } from "lucide-react";
import { Boxes } from "lucide-react";

export type DashboardNavItem = {
  labelKey: string;
  label: string;
  href: string;
  icon: LucideIcon;
};

export const generatedDashboardNav: DashboardNavItem[] = [];
`;
}

